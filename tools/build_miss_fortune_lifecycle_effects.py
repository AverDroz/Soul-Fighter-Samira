"""Bake Skin69 Death and Respawn particles and Respawn gun sockets for Isaac."""

import argparse
import json
from pathlib import Path
import sys
from zipfile import ZipFile

import numpy as np
from PIL import Image

from build_miss_fortune_effects import DESTINATION, additive_to_rgba, checked_asset, decode, write_atlas
from build_miss_fortune_joke_effects import EFFECTS_BIN, emitter_asset_paths, find_emitter
from build_miss_fortune_recall_effects import project_mesh
from build_miss_fortune_ultimate_effects import ZIP_SHA256
from import_miss_fortune_assets import GRAPH_BIN, GRAPH_KEY, SKIN_BIN, load_skin_entries
from import_yone_assets import archive_hash, binfile, read_bin


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src/samira/external"))
from model import Model


ATLAS = "lifecycle_effects"
DEATH = 0x7D9B23B9
RESPAWN = 0xD3B57C7E
DEATH_STATE = 0xBD28BD4D
RESPAWN_STATE = 0x9F77283F
FPS = 30
RESPAWN_BONES = {
    10: ("C_guns23_L_jt_10", "C_guns23_R_jt_10"),
    28: ("B_guns24_L_jt_3", "B_guns24_R_jt_3"),
    44: ("A_guns25_L_jt_2", "A_guns25_R_jt_2"),
}
SOURCES = {
    "DeathRibbon": (DEATH, ("Vertical_Glow_16",)),
    "DeathBand": (DEATH, ("Arctic_Bands",)),
    "DeathEmbers": (DEATH, ("AuroraBackdropStars",)),
    "DeathGroundFlash": (DEATH, ("blast", "blast1")),
    "RespawnMuzzle": (RESPAWN, ("Muzzle_Add_Vert",)),
    "RespawnFlash": (RESPAWN, ("Flash1",)),
}
MESH_WIDTHS = {"DeathRibbon": 24, "DeathBand": 20}


def graph_events(clip, resource):
    events = {}
    for event in clip.getv("mEventDataMap").values():
        effect = event.getv("mEffectKey")
        if effect is not None and effect.h == resource:
            frame = int(event.getv("mStartFrame", 0))
            events[frame] = [link.getv(0xEB880965).h for link in event.getv(0x60645D6A)]
    return events


def emitter_metadata(emitter):
    values = {}
    for field in ("particleLifetime", "rate", "emitterPosition", "birthVelocity",
                  "birthColor", "color", "birthScale0", "scale0", "birthRotation0", "uvScale"):
        value = emitter.getv(field)
        if value is None:
            continue
        base = value.getv(0xB4B427AA)
        curve = value.getv(0xBC037DE7)
        parameters = {"value": base} if base is not None else {}
        if curve is not None:
            parameters["keys"] = list(zip(curve.getv(0x5D68EEB5), curve.getv(0x34474C3B)))
        values[field] = parameters
    return {
        "emitter": emitter.getv("emitterName"),
        "delay_seconds": emitter.getv(0x22E763BC, 0),
        "emitter_lifetime_seconds": emitter.getv("lifetime"),
        **values,
    }


def bake_sprite(name, emitter, archive, hashes):
    texture_path, mesh_path = emitter_asset_paths(emitter)
    image = decode(checked_asset(archive, hashes, texture_path))
    source_size = image.size
    columns, rows = map(int, emitter.getv("texDiv", (1, 1)))
    if image.width % columns or image.height % rows:
        raise ValueError(f"Invalid lifecycle sheet grid for {name}")
    sample = (0, 0, image.width // columns, image.height // rows)
    uv = emitter.getv("uvScale")
    if uv is not None:
        u, v = uv.getv(0xB4B427AA)
        sample = (0, 0, round(sample[2] * u), round(sample[3] * v))
    image = image.crop(sample)
    transforms = []
    if (columns, rows) != (1, 1):
        transforms.append("Use the first cell of the source flipbook")
    if mesh_path:
        mesh = checked_asset(archive, hashes, mesh_path)
        image, _ = project_mesh(mesh, image, "XY", 90, MESH_WIDTHS[name])
        transforms.append("Project the textured SCB from its YZ side")
    if image.getchannel("A").getextrema() == (255, 255):
        image = additive_to_rgba(image)
        transforms.append("Convert additive RGB to straight RGBA")
    bounds = image.getchannel("A").getbbox()
    if bounds is None:
        raise ValueError(f"No visible source pixels for {name}")
    image = image.crop(bounds)
    metadata = {
        "sources": [{"path": path, "sha256": hashes[path]} for path in (texture_path, mesh_path) if path],
        "source_texture_size": source_size,
        "source_sample_bounds": sample,
        "alpha_crop_bounds": bounds,
        "sprite_size": image.size,
        "pivot": (image.width // 2, image.height // 2),
        "transforms": transforms,
    }
    return image, metadata


def respawn_tracks(model_path, frame_bones):
    model = Model(model_path, hero="mf")
    duration = model.durations["respawn"]
    if model.rig_events.get("frames_per_second") != FPS or duration * FPS < max(frame_bones):
        raise ValueError("Unexpected Skin69 Respawn clip timing")
    lines = ["-- Generated by tools/build_miss_fortune_lifecycle_effects.py from Skin69 Respawn.",
             "-- Each socket is {x,y,z,dx,dy,dz} in rig units. Direction is bone-local -Z.",
             "return {", "    respawn = {"]
    for frame, bones in frame_bones.items():
        phase = frame / (FPS * duration)
        pose = model.anchor_motion(model.sample("respawn", phase), "respawn")
        matrices = model.world_matrices(pose, "respawn", phase)
        lines.append(f"        [{frame}] = {{")
        for bone in bones:
            matrix = matrices[model.node_names[bone]]
            direction = -matrix[:3, 2]
            length = np.linalg.norm(direction)
            if not np.isfinite(matrix).all() or length < 1e-6:
                raise ValueError(f"Invalid Respawn transform for {bone} at frame {frame}")
            position = ",".join(f"{value:.4f}" for value in matrix[:3, 3])
            axis = ",".join(f"{value:.6f}" for value in direction / length)
            lines.append(f"            {{{position},{axis}}},")
        lines.append("        },")
    return "\n".join((*lines, "    },", "}", ""))


def build(abilities_zip, model_path):
    if archive_hash(abilities_zip) != ZIP_SHA256:
        raise ValueError("Unexpected Skin69 abilities ZIP SHA-256")
    images, sprite_metadata = {}, {}
    with ZipFile(abilities_zip) as archive:
        hashes = json.loads(archive.read("manifest.json"))["assets"]
        graph = read_bin(checked_asset(archive, hashes, GRAPH_BIN), GRAPH_KEY)
        clips = graph.getv("mClipDataMap")
        death = graph_events(clips[DEATH_STATE], DEATH)
        respawn = graph_events(clips[RESPAWN_STATE], RESPAWN)
        expected = {frame: [binfile.compute_binhash(bone) for bone in bones]
                    for frame, bones in RESPAWN_BONES.items()}
        if death != {0: [0x96B05E9E]} or respawn != expected:
            raise ValueError("Unexpected Skin69 lifecycle cue timing or bones")
        resolver = load_skin_entries(checked_asset(archive, hashes, SKIN_BIN))[0x391ED45D].getv(0xD2F58721)
        effects = load_skin_entries(checked_asset(archive, hashes, EFFECTS_BIN))
        for name, (resource, names) in SOURCES.items():
            emitters = [find_emitter(resolver, effects, resource, (), label)[0] for label in names]
            images[name], metadata = bake_sprite(name, emitters[0], archive, hashes)
            if any(emitter_asset_paths(emitter) != emitter_asset_paths(emitters[0]) for emitter in emitters):
                raise ValueError(f"Mismatched source textures for {name}")
            record = resolver[resource].h
            sprite_metadata[name] = {
                "resource": f"{resource:08x}", "entry": f"{record:08x}",
                "effect": effects[record].getv("particleName"),
                "emitters": [emitter_metadata(emitter) for emitter in emitters],
                **metadata,
            }

    tracks = respawn_tracks(model_path, RESPAWN_BONES)
    write_atlas(images, ATLAS, (512, 256), "DeathRibbon")
    metadata = {
        "archive": "MVP-T1-Miss-Fortune-Skin69-Abilities.zip",
        "archive_sha256": ZIP_SHA256,
        "definitions": [{"path": path, "sha256": hashes[path]} for path in (GRAPH_BIN, SKIN_BIN, EFFECTS_BIN)],
        "death": {"state": f"{DEATH_STATE:08x}", "cue_frame": 0, "bone": "C_BUFFBONE_GLB_LAYOUT_LOC"},
        "respawn": {"state": f"{RESPAWN_STATE:08x}", "frames_per_second": FPS, "sockets": RESPAWN_BONES,
                    "direction": "normalized anchored rig transform of gun socket local -Z",
                    "converted_rig_sha256": archive_hash(model_path)},
        "crop_format": "Pixel bounds with exclusive right and bottom. Alpha crop is relative to the sampled image or mesh projection.",
        "sprites": sprite_metadata,
    }
    (DESTINATION / f"{ATLAS}.provenance.json").write_text(json.dumps(metadata, indent=2) + "\n",
                                                          encoding="utf-8", newline="\n")
    tracks_path = DESTINATION.parents[2] / "miss_fortune_lifecycle_tracks.lua"
    tracks_path.write_text(tracks, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("abilities_zip", type=Path)
    parser.add_argument("--model", type=Path, default=ROOT / "assets/mf-local/mf.glb")
    args = parser.parse_args()
    build(args.abilities_zip, args.model)
