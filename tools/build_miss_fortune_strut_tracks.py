"""Sample the two authored Skin69 gun attachment points at the native sprite poses."""

import re

from build_miss_fortune_native_actions import GLB, LOOPS, MOD, Model


ATTACHMENTS = ("BUFFBONE_GLB_WEAPON_1", "BUFFBONE_CSTM_WEAPON_2")


def build():
    model = Model(GLB, hero="mf")
    count_file = MOD / "miss_fortune_sprite_frames.lua"
    counts = dict(re.findall(r"^\s+(\w+)\s*=\s*(\d+),$", count_file.read_text(encoding="utf-8"), re.M))
    if counts.keys() != model.durations.keys():
        raise ValueError("The native atlas and Skin69 rig contain different clips")
    bones = [model.node_names[name] for name in ATTACHMENTS]
    output = ["-- Generated by tools/build_miss_fortune_strut_tracks.py from Skin69.", "return {"]
    for clip, value in counts.items():
        count = int(value)
        divisor = count if clip in LOOPS else count - 1
        output.append(f"    {clip}={{")
        for frame in range(count):
            phase = frame / divisor
            if not model.visibility(clip, phase).get("A_Gun25", True):
                output.append("        false,")
                continue
            pose = model.anchor_motion(model.sample(clip, phase), clip)
            positions = model.world_matrices(pose, clip, phase)[bones, :3, 3]
            numbers = ",".join(f"{float(value):.2f}" for value in positions.flat)
            output.append(f"        {{{numbers}}},")
        output.append("    },")
    output.append("}")
    (MOD / "miss_fortune_strut_tracks.lua").write_text("\n".join(output) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    build()
