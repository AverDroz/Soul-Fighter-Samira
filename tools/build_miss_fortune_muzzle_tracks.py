"""Sample Skin69 weapon sockets on the same timeline as the native action atlas."""

import argparse
import json
from pathlib import Path
import re
import sys
from zipfile import ZipFile

import numpy as np

from build_miss_fortune_effects import checked_asset
from build_miss_fortune_ultimate_effects import ZIP_SHA256
from import_miss_fortune_assets import GRAPH_BIN, GRAPH_KEY, SKIN_BIN, load_skin_entries
from import_yone_assets import archive_hash, binfile, read_bin


ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / "src/samira-testroom/mod"
sys.path.insert(0, str(ROOT / "src/samira/external"))
from model import Model


RIGHT = "BUFFBONE_CSTM_WEAPON_MUZZLE_1"
LEFT = "BUFFBONE_CSTM_WEAPON_MUZZLE_2"
R_RIGHT = "BUFFBONE_GLB_WEAPON_1"
R_LEFT = "BUFFBONE_CSTM_WEAPON_2"
WEAPON_BASE = {RIGHT: R_RIGHT, LEFT: R_LEFT}
SINGLE_SHOTS = {
    "attack": (0x3EE785B1, 0x7495D294, 7, (RIGHT,)),
    "attack2": (0xF0462CF0, 0x7495D294, 7, (LEFT,)),
    "crit": (0x644E4E20, 0x7C0942A9, 7, (RIGHT, LEFT)),
    "q": (0xB2F63868, 0x9C2A03A4, 6, (RIGHT,)),
}
R_GROUP = 0xB7F64047
R_WINDUP = 0x34EDFA7B
R_LOOP = 0xA98DAC96
R_CAST = 0xB5D8A829
R_CUES = [(4, R_RIGHT), (12, R_LEFT), (19, R_RIGHT), (27, R_LEFT),
          (35, R_RIGHT), (43, R_LEFT), (51, R_RIGHT), (59, R_LEFT)]


def effect_cues(clip, resource, bone_names):
    cues = []
    for key, event in clip.getv("mEventDataMap", {}).items():
        effect = event.getv("mEffectKey")
        if effect is None or effect.h != resource:
            continue
        frame = int(event.getv("mStartFrame", 0))
        for link in event.getv(0x60645D6A):
            bone = bone_names[link.getv(0xEB880965).h]
            cues.append((frame, key.h, bone))
    return sorted(cues)


def sampled_rows(model, clip, count, sockets):
    muzzle_indices = [model.node_names[socket] for socket in sockets]
    base_indices = [model.node_names[WEAPON_BASE[socket]] for socket in sockets]
    for muzzle, base in zip(muzzle_indices, base_indices, strict=True):
        if model.parents[muzzle] != model.parents[base]:
            raise ValueError(f"Unexpected weapon socket hierarchy for {clip}")

    divisor = count if clip == "r" else count - 1
    rows = []
    for index in range(count):
        phase = index / divisor
        pose = model.anchor_motion(model.sample(clip, phase), clip)
        matrices = model.world_matrices(pose, clip, phase)
        row = []
        for muzzle, base in zip(muzzle_indices, base_indices, strict=True):
            position = matrices[muzzle, :3, 3]
            axis = -matrices[muzzle, :3, 2]
            forward = position - matrices[base, :3, 3]
            axis_length = np.linalg.norm(axis)
            forward_length = np.linalg.norm(forward)
            if not np.isfinite([position, axis, forward]).all() or min(axis_length, forward_length) < 1e-6:
                raise ValueError(f"Invalid muzzle transform for {clip} atlas frame {index}")
            direction = axis / axis_length
            if direction @ (forward / forward_length) < .98:
                raise ValueError(f"Gun axis disagrees with its barrel socket for {clip} atlas frame {index}")
            row.append((position, direction))
        rows.append(row)
    return rows


def format_socket(position, direction):
    xyz = ",".join(f"{value:.4f}" for value in position)
    axis = ",".join(f"{value:.6f}" for value in direction)
    return f"{{{xyz},{axis}}}"


def build(abilities_zip, model_path, output):
    if archive_hash(abilities_zip) != ZIP_SHA256:
        raise ValueError("Unexpected Skin69 abilities ZIP SHA-256")
    model = Model(model_path, hero="mf")
    bone_names = {binfile.compute_binhash(bone): bone for bone in model.node_names}
    counts = dict(re.findall(r"^\s+(\w+)\s*=\s*(\d+),$",
                             (MOD / "miss_fortune_sprite_frames.lua").read_text(encoding="utf-8"), re.M))
    preferred = {name: sockets for name, (_, _, _, sockets) in SINGLE_SHOTS.items()}
    preferred["r"] = (RIGHT, LEFT)

    lines = ["-- Generated by tools/build_miss_fortune_muzzle_tracks.py from Skin69.",
             "-- Each one-based row matches the native action atlas. Add 1 to Sprites.sample's frame index.",
             "-- Each socket is {x,y,z,dx,dy,dz} in anchored rig units. Direction is bone-local -Z.",
             f"-- Abilities ZIP SHA-256 {ZIP_SHA256}", f"-- GLB SHA-256 {archive_hash(model_path)}"]
    with ZipFile(abilities_zip) as archive:
        hashes = json.loads(archive.read("manifest.json"))["assets"]
        graph = read_bin(checked_asset(archive, hashes, GRAPH_BIN), GRAPH_KEY)
        resolver = load_skin_entries(checked_asset(archive, hashes, SKIN_BIN))[0x391ED45D].getv(0xD2F58721)
        clips = graph.getv("mClipDataMap")
        lines.append(f"-- Animation graph SHA-256 {hashes[GRAPH_BIN]}")
        for name, (state, resource, frame, sockets) in SINGLE_SHOTS.items():
            cues = effect_cues(clips[state], resource, bone_names)
            if [(offset, bone) for offset, _, bone in cues] != [(frame, bone) for bone in sockets]:
                raise ValueError(f"Unexpected Skin69 muzzle cues for {name}")
            source = clips[state].getv("mAnimationResourceData").getv("mAnimationFilePath").lower()
            if model.rig_events["states"][f"{state:08x}"]["source_anm"] != source:
                raise ValueError(f"Imported rig does not bind {name} to its source clip")
            event_keys = "/".join(f"{key:08x}" for _, key, _ in cues)
            socket_list = "/".join(sockets)
            lines.append(f"-- {name}: state {state:08x}, frame {frame}, event {event_keys}, "
                         f"effect {resource:08x} -> {resolver[resource].h:08x}, sockets {socket_list}.")
            lines.append(f"-- {source} SHA-256 {hashes[source]}")

        if [clip.h for clip in clips[R_GROUP].getv(0x078CAFD9)] != [R_WINDUP, R_LOOP]:
            raise ValueError("Unexpected Bullet Time animation group")
        cues = effect_cues(clips[R_WINDUP], R_CAST, bone_names)
        if [(frame, bone) for frame, _, bone in cues] != R_CUES or effect_cues(clips[R_LOOP], R_CAST, bone_names):
            raise ValueError("Unexpected Bullet Time weapon bindings")
        source = clips[R_LOOP].getv("mAnimationResourceData").getv("mAnimationFilePath").lower()
        state = model.rig_events["states"][f"{R_LOOP:08x}"]
        if state["source_anm"] != source or state["clip"] != "r":
            raise ValueError("Imported rig does not bind Bullet Time to its genuine loop")
        source_hash = model.rig_events["supplemental_animation_source"]["entries"][source]
        lines.append(f"-- r: windup {R_WINDUP:08x}, loop {R_LOOP:08x}, effect {R_CAST:08x} -> "
                     f"{resolver[R_CAST].h:08x}; the loop uses right then left barrel tips on the same weapon branches.")
        for frame, key, bone in cues:
            lines.append(f"-- Windup frame {frame}, event {key:08x}, joint {bone}.")
        lines.append(f"-- {source} SHA-256 {source_hash}")

    lines.append("return {")
    for clip, sockets in preferred.items():
        lines.append(f"    {clip} = {{")
        for row in sampled_rows(model, clip, int(counts[clip]), sockets):
            values = ", ".join(format_socket(position, direction) for position, direction in row)
            lines.append("        {" + values + "},")
        lines.append("    },")
    output.write_text("\n".join((*lines, "}", "")), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("abilities_zip", type=Path)
    parser.add_argument("--model", type=Path, default=ROOT / "assets/mf-local/mf.glb")
    args = parser.parse_args()
    build(args.abilities_zip, args.model, MOD / "miss_fortune_muzzle_tracks.lua")
