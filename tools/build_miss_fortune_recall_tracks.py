"""Sample Skin69's authored Recall attachment joints for native Isaac effects."""

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src/samira/external'))
from model import Model


CLIP = 'recall_cinematic'
ATTACHMENTS = {
    'road': ('VFX_buffbone01', 0, 239),
    'spear': ('VFX_buffbone02', 9, 38),
    'arrow': ('VFX_buffbone03', 57, 76),
    'balloon': ('VFX_buffbone04', 103, 137),
    'fmvp': ('Miss_FMVP_Trophy_2025', 138, 260),
    'cup2023': ('Miss_Trophy_2023', 230, 260),
    'cup2024': ('Miss_Trophy_2024', 230, 260),
    'cup2025': ('Miss_Trophy_2025', 230, 260),
    'shot35Left': ('C_guns23_L_jt_10', 35, 37),
    'shot35Right': ('C_guns23_R_jt_10', 35, 37),
    'shot68': ('BUFFBONE_CSTM_WEAPON_MUZZLE_2', 68, 70),
    'shot105': ('BUFFBONE_CSTM_WEAPON_MUZZLE_2', 105, 107),
    'shot110': ('BUFFBONE_CSTM_WEAPON_MUZZLE_1', 110, 112),
}


def build(model_path, output):
    model = Model(model_path, hero='mf')
    duration = round(model.durations[CLIP] * 30)
    tracks = {name: [] for name in ATTACHMENTS}
    if duration != 260 or any(bone not in model.node_names for bone, *_ in ATTACHMENTS.values()):
        raise ValueError('Recall source duration or attachment joints changed')
    for frame in range(duration + 1):
        phase = frame / duration
        pose = model.anchor_motion(model.sample(CLIP, phase), CLIP)
        matrices = model.world_matrices(pose, CLIP, phase)
        for name, (bone, start, end) in ATTACHMENTS.items():
            if start <= frame <= end:
                matrix = matrices[model.node_names[bone]]
                sample = tuple(round(float(value), 2) for value in matrix[:3, 3])
                if name.startswith('shot'):
                    sample += tuple(round(float(value), 5) for value in -matrix[:3, 2])
                tracks[name].append(sample)

    rows = ['-- Generated by tools/build_miss_fortune_recall_tracks.py from Skin69 Recall_Real.',
            '-- Gunshot rows include the attachment position followed by its forward axis.', 'return {']
    for name, (_, start, end) in ATTACHMENTS.items():
        samples = tracks[name]
        if len(samples) != end - start + 1:
            raise ValueError(f'Incomplete source samples for {name}')
        rows.append(f'    {name} = {{first={start}, positions={{')
        for index in range(0, len(samples), 4):
            vectors = ('{' + ','.join(f'{value:g}' for value in row) + '}' for row in samples[index:index + 4])
            rows.append('        ' + ', '.join(vectors) + ',')
        rows.append('    }},')
    rows.append('}')
    output.write_text('\n'.join(rows) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    build(ROOT / 'assets/mf-local/mf.glb',
          ROOT / 'src/samira-testroom/mod/miss_fortune_recall_tracks.lua')
